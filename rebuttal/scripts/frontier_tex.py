"""Write the frontier tables of Appendix B from the databook: tables/frontier_summary.tex and tables/frontier_runs.tex."""
import collections
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "paper_latex" / "tables"
ROWS = [r for r in csv.DictReader(open(ROOT / "results/databook/frontier_cells.csv")) if "x86" not in r["arm"]]
ARMS = {  # arm -> (model, harness), in table order
    "thin-gpt-6.1-sol": ("gpt-6.1-sol", "ours"),
    "codex-gpt-6.1-sol": ("gpt-6.1-sol", "Codex CLI"),
    "codex-gpt-6.1-sol-nudge": ("gpt-6.1-sol", "Codex CLI + prompts"),
    "thin-gpt-6-astra": ("gpt-6-astra", "ours"),
    "codex-gpt-6-astra": ("gpt-6-astra", "Codex CLI"),
    "thin-muse-wonder-1.0": ("Muse Wonder", "ours"),
    "miniswe": ("Muse Wonder", "mini-SWE-agent"),
}
TIER = {"run": "Run", "retrain": "Retrain", "reimplement": "Reimplement"}
EXIT = {"natural": "agent ended the run", "submitted": "agent ended the run", "wall_clock": "time limit",
        "budget_exhausted": "GPU grant spent", "error": "harness error"}


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return round(100 * (c - h)), round(100 * (c + h))


def num(x):
    try:
        return float(x)
    except ValueError:
        return 0.0


by_arm = collections.defaultdict(list)
for r in ROWS:
    by_arm[r["arm"]].append(r)
unknown = set(by_arm) - set(ARMS)
assert not unknown, unknown

lines = []
for arm, (model, harness) in ARMS.items():
    rs = by_arm.get(arm, [])
    if not rs:
        continue
    n = len(rs)
    k = sum(r["reproduced"] == "True" for r in rs)
    lo, hi = wilson(k, n)
    mean = sum(num(r["score"]) for r in rs) / n
    ds = sum(num(r["dsv4"]) >= 8 for r in rs)
    mu = sum(num(r["muse"]) >= 8 for r in rs)
    lines.append(f"{model} & {harness} & {n} & {k} ({lo}--{hi}\\%) & {mean:.2f} & {ds} & {mu} \\\\")
SUMMARY_HEAD = r"""% generated by rebuttal/scripts/frontier_tex.py; do not edit
\begin{tabular}{@{}llrlrrr@{}}
\toprule
& & & & & \multicolumn{2}{c}{Reproduced on the same papers} \\
\cmidrule(l){6-7}
Model & Harness & Papers & \shortstack{Reproduced\\(95\% interval)} & \shortstack{Mean\\score} & \shortstack{DeepSeek-\\V4-Flash} & \shortstack{Muse Spark\\1.2} \\
\midrule
"""
(OUT / "frontier_summary.tex").write_text(SUMMARY_HEAD + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")

lines = []
for arm, (model, harness) in ARMS.items():
    for r in sorted(by_arm.get(arm, []), key=lambda r: r["paper"]):
        spent = 100 * num(r["spent_h100"]) / num(r["budget_h100"]) if num(r["budget_h100"]) else 0.0
        verdict = r["verdict"].replace("_", " ")
        lines.append(
            f"{model} & {harness} & {r['paper']} & {TIER[r['orig_tier']]} & {verdict} ({r['score']}) & {spent:.1f} & "
            f"{EXIT.get(r['exit_reason'], r['exit_reason'].replace('_', ' '))} \\\\"
        )
RUNS_HEAD = r"""% generated by rebuttal/scripts/frontier_tex.py; do not edit
{\scriptsize
\setlength{\tabcolsep}{3pt}
\begin{longtable}{@{}lllllrl@{}}
\toprule
Model & Harness & Paper & Tier & Verdict (score) & Grant spent (\%) & Exit reason \\
\midrule
\endhead
\endfoot
\bottomrule
\noalign{\vskip 6pt}
\caption{Every graded frontier run with its verdict, the share of its GPU
grant it spent, and its exit reason.}
\label{tab:frontier-runs} \\
\endlastfoot
"""
(OUT / "frontier_runs.tex").write_text(RUNS_HEAD + "\n".join(lines) + "\n\\end{longtable}\n}\n")
print(len(ROWS), "rows;", sorted(collections.Counter(r["exit_reason"] for r in ROWS).items()))
